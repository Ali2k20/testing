import type { Product, Review, SizeOption } from "./types";

/** Gulf abaya sizing. Length is shoulder to hem, the number customers ask for. */
function abayaSizes(stock: number[]): SizeOption[] {
  const labels = ["50", "52", "54", "56", "58", "60"];
  const lengths = [132, 137, 142, 147, 152, 157];
  return labels.map((label, index) => ({
    label,
    lengthCm: lengths[index],
    stock: stock[index] ?? 0,
  }));
}

function letterSizes(stock: number[]): SizeOption[] {
  return ["S", "M", "L", "XL"].map((label, index) => ({
    label,
    stock: stock[index] ?? 0,
  }));
}

function oneSize(stock: number): SizeOption[] {
  return [{ label: "One size", stock }];
}

function review(
  author: string,
  emirate: string,
  rating: number,
  title: string,
  body: string,
  date: string,
): Review {
  return { author, emirate, rating, title, body, date, verified: true };
}

