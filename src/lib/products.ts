export const productBySlug = new Map(products.map((product) => [product.slug, product]));

export function getProduct(slug: string) {
  return productBySlug.get(slug);
}

export function getProducts(slugs: string[]) {
  return slugs
    .map((slug) => productBySlug.get(slug))
    .filter((product): product is Product => Boolean(product));
}

export function productsInCollection(slug: string) {
  return products.filter((product) => product.collections.includes(slug));
}

export function totalStock(product: Product) {
  return product.sizes.reduce((sum, size) => sum + size.stock, 0);
}

export function ratingFor(product: Product) {
  if (product.reviews.length === 0) return { average: 0, count: 0 };
  const total = product.reviews.reduce((sum, r) => sum + r.rating, 0);
  return {
    average: Math.round((total / product.reviews.length) * 10) / 10,
    count: product.reviews.length,
  };
}

/** Aggregate rating across the catalogue, used for the homepage social proof. */
export function catalogueRating() {
  const all = products.flatMap((product) => product.reviews);
  const total = all.reduce((sum, r) => sum + r.rating, 0);
  return {
    average: Math.round((total / all.length) * 10) / 10,
    count: all.length,
  };
}

